/**
 * Combines ordered migration files for one-shot apply in Supabase SQL Editor.
 * Run: npm run db:combine-migrations
 * Output: supabase/apply-all-migrations.sql
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const MIGRATIONS_DIR = resolve(import.meta.dirname, '../supabase/migrations');
const OUTPUT = resolve(import.meta.dirname, '../supabase/apply-all-migrations.sql');

const files = readdirSync(MIGRATIONS_DIR)
  .filter((name) => name.endsWith('.sql'))
  .sort();

const parts = [
  '-- Quantix V1 — apply all migrations in Supabase SQL Editor',
  '-- Generated by scripts/combine-migrations.mjs',
  '-- Run this once on a new Supabase project before seeding or provisioning users.',
  '',
];

for (const file of files) {
  parts.push(`-- >>> BEGIN ${file}`);
  parts.push(readFileSync(resolve(MIGRATIONS_DIR, file), 'utf8').trim());
  parts.push(`-- <<< END ${file}`);
  parts.push('');
}

writeFileSync(OUTPUT, `${parts.join('\n')}\n`, 'utf8');
console.log(`Wrote ${OUTPUT} (${files.length} migrations).`);
